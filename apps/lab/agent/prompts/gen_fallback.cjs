/* Agent — prompts/gen_fallback.cjs (AG29). Rebuild prompts/prompt_fallback.js from prompts/prompt_*.txt.
   The .txt files are the only copy of the wording. The fallback script is generated so file:// (where fetch of a
   local .txt is blocked) and a failed asset load still have the same text. No hand-maintained duplicate strings.
   Usage (from apps/lab/agent): node prompts/gen_fallback.cjs          write prompts/prompt_fallback.js
                                node prompts/gen_fallback.cjs --check  exit 1 if the file is stale
                                node prompts/gen_fallback.cjs --stdout print the file, write nothing */
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const names = ['prompt_system.txt', 'prompt_files.txt', 'prompt_shell.txt', 'prompt_web.txt', 'prompt_memory.txt', 'prompt_settings.txt'];
function build() {
  const bag = {};
  names.forEach(function (n) { bag[n] = fs.readFileSync(path.join(dir, n), 'utf8'); });
  return '/* Generated by prompts/gen_fallback.cjs from prompts/prompt_*.txt. Do not edit by hand. */\n' +
    'HR.promptFiles = ' + JSON.stringify(bag, null, 2) + ';\n';
}
const body = build();
const out = path.join(dir, 'prompt_fallback.js');
if (process.argv.indexOf('--stdout') >= 0) { process.stdout.write(body); }
else if (process.argv.indexOf('--check') >= 0) {
  const cur = fs.readFileSync(out, 'utf8');
  if (cur !== body) { process.stderr.write('prompt_fallback.js is stale; run: node prompts/gen_fallback.cjs\n'); process.exit(1); }
} else fs.writeFileSync(out, body);
