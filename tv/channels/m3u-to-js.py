#!/usr/bin/env python3
"""m3u-to-js.py (TV2): write <name>.m3u.js next to each <name>.m3u so tv-v1.html works from file://.

Each output sets  window.TV_M3U['<name>'] = "<raw M3U text>";  (JSON string, so quotes,
backslashes, backticks and ${ are all safe). Browsers block fetch() on file://, but a
<script> tag still loads, so tv-v1.js falls back to these files there.

Usage (inside tv/channels/):  python3 m3u-to-js.py            # home.m3u home-more.m3u kids.m3u
                              python3 m3u-to-js.py a.m3u b.m3u  # specific files
split-m3u.sh calls this at the end. Rerun it after hand-editing any .m3u. Do not edit the .m3u.js files.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = ['home.m3u', 'home-more.m3u', 'kids.m3u']

def convert(path):
    if not os.path.isabs(path):
        path = os.path.join(HERE, path)
    name = os.path.basename(path)[:-len('.m3u')] if path.endswith('.m3u') else os.path.basename(path)
    with open(path, encoding='utf-8', newline='') as f:  # keep raw line endings
        text = f.read()
    lit = json.dumps(text, ensure_ascii=False).replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    out = path + '.js'
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* GENERATED by m3u-to-js.py from %s (TV2). Do not edit; edit the .m3u / CSV and rerun. */\n'
                % os.path.basename(path))
        f.write('window.TV_M3U = window.TV_M3U || {};\n')
        f.write('window.TV_M3U[%s] = %s;\n' % (json.dumps(name), lit))
    print('wrote', os.path.relpath(out, HERE))

if __name__ == '__main__':
    for p in (sys.argv[1:] or DEFAULT):
        convert(p)
