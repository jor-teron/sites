#!/usr/bin/env python3
"""R33c: writes hub/core/hub_appindex.js (app id -> [category, entry, name, icon, newTab(, description)]) from the ids the Hub
really gives once every category CSV is registered. Run after any change to an
apps/<cat>/<cat>-apps.csv (needs Playwright):  python3 hub/core/hub_appindex_gen.py
R47: the same run first rewrites hub/core/hub_catalog.js (window.SITES_CSV = {category: exact CSV text})
from hub_config.js HUB_CAT_CSV, so the Hub can list apps without a web server (file://). The CSVs stay
the source of truth: edit a CSV, then rerun this script. (--catalog-only: skip the index, no Playwright.)
A stale index is safe (the Hub falls back to waiting for the CSVs) but slower on a first visit;
the Hub logs 'hub_appindex.js is out of date' in the console when it is.
H48c: optional 'description' column (LAST column of a category CSV, named in its header row; one
short line, no commas). Rows with a non-empty description get it as a 6th item; rows without one
(or CSVs without the column) stay 5 items, so the script works unchanged when the column is absent.
The Hub (hub.js __hubAppIndex) already reads it; this script also fills it from the CSVs itself, so
an older cached list in the browser cannot drop it."""
import functools, http.server, json, os, re, sys, threading
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))

# ---- R47: hub_catalog.js (no Playwright needed) ----
def js_template(t):
    """Exact text inside a JS template literal: escape \\, ` and ${."""
    return t.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')
cfg = open(os.path.join(ROOT, 'hub', 'core', 'hub_config.js'), encoding='utf-8').read()
block = re.search(r'HUB_CAT_CSV\s*=\s*\{(.*?)\}', cfg, re.S).group(1)
cats = re.findall(r"""['"]?([\w-]+)['"]?\s*:\s*['"]([^'"]+\.csv)['"]""", block)
parts = []
for cat, path in cats:
    with open(os.path.join(ROOT, path), encoding='utf-8', newline='') as f: text = f.read()
    parts.append('  %s: `%s`' % (json.dumps(cat), js_template(text)))
open(os.path.join(ROOT, 'hub', 'core', 'hub_catalog.js'), 'w', encoding='utf-8', newline='\n').write(
    "/*\n * Hub catalog (hub/core/hub_catalog.js), R47. GENERATED by hub_appindex_gen.py, do not edit.\n"
    " * category -> the EXACT text of its apps CSV (hub_config.js HUB_CAT_CSV), so the menu / tiles work\n"
    " * without a web server (file://, where fetch() of local files is blocked). The CSVs are the source\n"
    " * of truth: after editing any apps/<cat>/<cat>-apps.csv rerun  python3 hub/core/hub_appindex_gen.py\n"
    " * Online the Hub still fetches the CSV first, so a stale catalog only matters on file://.\n */\n"
    "window.SITES_CSV = Object.assign(window.SITES_CSV || {}, {\n" + ',\n'.join(parts) + "\n});\n")
print(len(cats), 'category CSVs -> hub_catalog.js')
if '--catalog-only' in sys.argv: sys.exit(0)

from playwright.sync_api import sync_playwright
class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(Quiet, directory=ROOT))
threading.Thread(target=srv.serve_forever, daemon=True).start()
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page()
    pg.goto('http://127.0.0.1:%d/hub.html' % srv.server_port)
    pg.wait_for_function('window.__hubAppIndex && Object.keys(window.__hubAppIndex()).length > 0')
    pg.wait_for_timeout(4500)   # every CSV registered (4 s cap)
    idx = pg.evaluate('window.__hubAppIndex()'); b.close()
srv.shutdown()

# ---- H48c: optional description column -> 6th item (only when present and non-empty) ----
def csv_descriptions():
    """entry path (as the Hub writes it) -> description, from every category CSV with a header row
    naming 'description'. Mirrors shared/tiles/tiles.js parse(): '#' comments, cells split on ','."""
    out = {}
    for cat, path in cats:
        with open(os.path.join(ROOT, path), encoding='utf-8') as f:
            rows = [[c.strip() for c in l.strip().split(',')] for l in f if l.strip() and not l.strip().startswith('#')]
        if not rows or rows[0][0].lower() != 'name' or len(rows[0]) < 2 or rows[0][1].lower() != 'path':
            continue                                    # no header row = default columns, no description
        head = [h.lower() for h in rows[0]]
        if 'description' not in head: continue
        i_p, i_d = head.index('path'), head.index('description')
        base = os.path.dirname(path)
        for r in rows[1:]:
            d = r[i_d] if i_d < len(r) else ''
            if not d or i_p >= len(r) or not r[i_p]: continue
            p = r[i_p]
            e = os.path.normpath(os.path.join(base, p)).replace(os.sep, '/') + ('/' if p.endswith('/') else '')
            out.setdefault(e, d)                        # first CSV wins (like the Hub: first registration)
    return out
descs = csv_descriptions()
for k, v in idx.items():
    d = descs.get(v[1])
    if d and len(v) == 5: v.append(d)
    elif len(v) > 5 and not v[5]: del v[5:]
rows = ',\n'.join('  %s: %s' % (json.dumps(k), json.dumps(v)) for k, v in idx.items())
open(os.path.join(ROOT, 'hub', 'core', 'hub_appindex.js'), 'w').write(
    "/*\n * Hub app index (hub/core/hub_appindex.js), R33c. GENERATED by hub_appindex_gen.py, do not edit.\n"
    " * id -> [category, entry, name, icon, newTab(, description)] for every category-CSV app, so a first-visit #hash / last app / saved\n"
    " * window opens as soon as ITS CSV is in. Stale = safe: the Hub then waits for the CSVs (R33b).\n"
    " * H48c: the 6th item (description) is there only when the app's CSV row has one (optional last column).\n */\n"
    "window.HUB_APP_INDEX = {\n" + rows + "\n};\n")
print(len(idx), 'apps')
